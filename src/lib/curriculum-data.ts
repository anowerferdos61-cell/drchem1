export const LAB_BY_ID = new Map(ALL_LABS.map((l) => [l.id, l]));

// All board/practical labs live in the Practical Lab Room.
export const PRACTICAL_LABS = ALL_LABS.filter((l) => l.isCoreBoard);

export function getChapterMeta(chapterNumber: number | string): ChapterMeta | undefined {
  const num = typeof chapterNumber === "string" ? parseInt(chapterNumber, 10) : chapterNumber;
  return CHAPTERS.find((c) => c.number === num);
}

export function getLabsForChapter(chapterNumber: number | string): LabMeta[] {
  const ch = getChapterMeta(chapterNumber);
  if (!ch) return [];
  return ch.labIds.map((id) => LAB_BY_ID.get(id)).filter(Boolean) as LabMeta[];
}
